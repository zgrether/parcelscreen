/**
 * The driveway quantity corrections, relief culverts and the "no practical drive" rule (owner, #99 decisions,
 * 2026-10-11; ENGINE_VERSION 11). Writes docs/studies/driveway-quantities.md:
 *  1. every fixture site's routes, before (engine 10, from driveway-quantities.before.json) and after: length, cost
 *     and cost per foot, culverts, the one scored;
 *  2. which sites trip the rule, their alternatives and the points they're scored on;
 *  3. the rankings before and after;
 *  4. Grayson's 1.28 ac site (engine 10's #1) as its driveway card reads now.
 * The before file was dumped from main at engine 10 (49456f5) with the same fields.
 *
 *   pnpm dw:quant
 */
import { readFileSync, writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { fmt } from "@/lib/format";
import { drivewayView } from "@/lib/report/driveway";
import { SCREEN_CONSTANTS } from "@/lib/screen/config";
import {
  practicalAlternatives,
  reliefCulverts,
  siteDriveways,
  type SiteDriveway,
} from "@/lib/screen/driveway";
import { ENGINE_VERSION } from "@/lib/screen/engine";
import { evaluateAt, routeContext } from "@/lib/screen/index";
import {
  chooseDriveway,
  drivewayPoints,
  isImpractical,
  overLimitPoints,
  practicalDriveway,
  withDrivewayCost,
  withoutVetoed,
} from "@/lib/screen/score";
import type { LatLon } from "@/lib/screen/util";
import { runFixture } from "../support/scenarios";

const DOC = "docs/studies/driveway-quantities.md";
const K = SCREEN_CONSTANTS.driveway;
const SLUGS = [
  ["ferney-creek-52-47A", "Ferney"],
  ["macks-mountain-35-3", "Macks"],
  ["grayson-mud-creek-6273", "Grayson"],
] as const;

interface Brief {
  lengthFt: number;
  costMid: number;
  culverts: number;
  switchbacks: number;
  maxGradePct: number;
  needsEasement: boolean;
  legal: boolean;
}
interface BeforeSite {
  rank: number;
  ll: LatLon;
  acres: number;
  score: number;
  drivewayPts: number;
  withinLimit: Brief | null;
  onParcel: Brief | "same" | null;
  scored: "withinLimit" | "onParcel";
}
const BEFORE = JSON.parse(readFileSync("test/tools/driveway-quantities.before.json", "utf8")) as Record<
  string,
  BeforeSite[]
> & { engine: number };

const k$ = (n: number) => `$${fmt(n / 1000)}k`;
const perFt = (cost: number, ft: number) => (ft > 0 ? `$${fmt(cost / ft)}` : "—");
const same = (a: LatLon, b: LatLon) => a[0] === b[0] && a[1] === b[1];

describe.runIf(import.meta.env.MODE === "dw-quant")("driveway quantities (#99 decisions)", () => {
  it("writes the study", async () => {
    const out: string[] = [
      '# Driveway quantities, relief culverts and "no practical drive"',
      "",
      `Generated by \`pnpm dw:quant\` (\`test/tools/driveway-quantities.test.ts\`), engine ${BEFORE.engine} → ` +
        `${ENGINE_VERSION}. The owner's #99 decisions (2026-10-11), on top of [the cost check](driveway-cost-check.md):`,
      "",
      "1. **The four quantity corrections.** The road's cut is a balanced half bench on side slopes under " +
        `${K.fullBenchSlopeDeg}° (W² tanθ / 8) and a full bench steeper (W² tanθ / 2); only the part of it below ` +
        "the soils' depth to bedrock is rock (the triangle's share below depth b of a cut H deep, ((H − b) / H)²: it " +
        `can't top 100% any more); stone is ${fmt(K.stoneDepthM / 0.0254)} in deep; geotextile only on bottomland ` +
        "and poorly drained soils.",
      "2. **Relief culverts** along the road by its grade over 30 m: " +
        K.reliefCulverts.everyFt
          .map(([upTo, ft], i, a) => `${i ? `${a[i - 1]![0]}–${upTo}%` : `≤ ${upTo}%`} every ${ft} ft`)
          .join(", ") +
        `, steeper every ${K.reliefCulverts.steeperFt} ft; on top of the entrance's and one at each drainage ` +
        "crossing. They have their own rate, `dw.reliefCulvertEach`, the culvert rate until the quote.",
      `3. **"No practical drive"** when the route a site is scored on costs more than ` +
        `${Math.round(K.impracticalShareOfReadyToBuild * 100)}% of the ready-to-build budget ($300k by default, so ` +
        `$225k): the site is scored on the cheaper (in points) of its alternatives, the route kept to the parcel at ` +
        `${K.practicalMaxPct}% and the route within the limit through the neighbours. The 20% veto still applies. The 15% alternative is a designed alignment: its over-limit term reads its design limit (+5 under a 10% limit), not the ungraded ground under it (option C).`,
      "",
      "Unit rates are unchanged (follow-up 47 waits for the quote). Costs are the middle of the card's ±30% range.",
      "",
    ];

    const trips: string[] = [];
    const rankings: string[] = [];
    let graysonCard: string[] = [];
    out.push("## 1. Every fixture route, before and after", "");
    out.push(
      "Each site's two candidates (A4): the cheapest route within the limit, and the cheapest kept to the parcel when " +
        "that one leaves it (over the limit when nothing within it reaches). **Bold**: the one scored. Culverts after: " +
        "entrance and crossings + relief.",
      "",
      "| Site (engine 10 rank) | Route | Length (ft) | Before | $/ft | After | $/ft | Culverts before → after | Switchbacks |",
      "|---|---|---|---|---|---|---|---|---|",
    );
    for (const [slug, name] of SLUGS) {
      const run = await runFixture(slug);
      const { result, session: s } = run;
      const ctx = routeContext(s);
      const sites = result.sites ?? [];
      const lls = sites.map((x) => x.ll);
      const routes = siteDriveways(ctx, s.roads ?? [], s.parcel, lls, s.config.roadMaxGradePct);
      const before = BEFORE[slug]!;
      const ready = s.config.budget.readyToBuild;
      const veto = s.config.roadVetoGradePct;
      const chosen = routes.map((r) => chooseDriveway(r, veto));
      const tripIdx = chosen.flatMap((c, i) => (isImpractical(c, ready) ? [i] : []));
      const alts = practicalAlternatives(
        ctx,
        s.roads ?? [],
        s.parcel,
        tripIdx.map((i) => lls[i]!),
        tripIdx.map((i) => routes[i]!),
        s.config.roadMaxGradePct,
      ).map((a) => withoutVetoed(a, veto));

      for (const b of before) {
        const i = sites.findIndex((x) => same(x.ll, b.ll));
        const r = routes[i]!;
        const label = `${name} #${b.rank} (${fmt(b.acres, 2)} ac)`;
        const row = (kind: string, was: Brief | null, now: SiteDriveway | null, scored: boolean) => {
          const rt = now?.route;
          if (!rt || !was) return;
          const relief = reliefCulverts(rt.profile);
          const bold = (t: string) => (scored ? `**${t}**` : t);
          out.push(
            `| ${label} | ${bold(`${kind}${rt.needsEasement ? " (easement)" : ""}${now.legal ? "" : ` (over: ${Math.round(rt.maxGrade * 100)}%)`}`)} | ` +
              `${fmt(rt.metrics.lengthFt)} | ${k$(was.costMid)} | ${perFt(was.costMid, was.lengthFt)} | ` +
              `${bold(k$(rt.cost.mid))} | ${perFt(rt.cost.mid, rt.metrics.lengthFt)} | ${was.culverts} → ` +
              `${rt.metrics.culverts} + ${relief} | ${rt.metrics.switchbacks} |`,
          );
        };
        const scoredNow = chosen[i]!;
        row("within the limit", b.withinLimit, r.withinLimit, scoredNow === r.withinLimit);
        if (b.onParcel !== "same" && r.onParcel !== r.withinLimit)
          row("kept to the parcel", b.onParcel, r.onParcel, scoredNow === r.onParcel);
      }

      // The rule.
      tripIdx.forEach((i, k) => {
        const b = before.find((x) => same(x.ll, sites[i]!.ll))!;
        const a = alts[k]!;
        const scored = practicalDriveway(chosen[i]!, a);
        const alt = (d: SiteDriveway | null, what: string) =>
          d?.route
            ? `${what} ${fmt(d.route.metrics.lengthFt)} ft, ${fmt(d.route.metrics.maxGradePct, 1)}% over 30 m, ${k$(d.route.cost.mid)}, ` +
              `${fmt(drivewayPoints(d), 1)} points (over-limit +${fmt(overLimitPoints(d), 1)})${d === scored ? " **(scored)**" : ""}`
            : "none";
        const c = chosen[i]!;
        // The site's score without the rule: re-costed on the chosen route instead.
        const sctx = { valleyFloorFt: s.valleyFloorFt ?? NaN, skyScore: result.sky?.score, cfg: s.config };
        const without = withDrivewayCost(sctx, sites[i]!, c).score;
        trips.push(
          `| ${name} #${b.rank} (${fmt(b.acres, 2)} ac) | ${k$(c.route!.cost.mid)}, ${fmt(drivewayPoints(c), 1)} points ` +
            `(over-limit +${fmt(overLimitPoints(c), 1)}) | ${alt(a.steeper, `at ${K.practicalMaxPct}%,`)} | ` +
            `${alt(a.easement, "via the neighbours,")} | ${sites[i]!.score} (#${i + 1}) / ${without} |`,
        );
      });

      // The rankings.
      rankings.push(
        `**${name}**: ` +
          sites
            .map((x, i) => {
              const b = before.find((y) => same(y.ll, x.ll))!;
              return `${i + 1}. ${fmt(x.acres, 2)} ac ${x.score} (was #${b.rank}, ${b.score}; driveway ${fmt(b.drivewayPts, 1)} → ${fmt(x.c.driveway, 1)} points)`;
            })
            .join(" · "),
        "",
      );

      // Grayson's engine-10 #1, as its card reads.
      if (slug === "grayson-mud-creek-6273") {
        const was1 = before.find((x) => x.rank === 1)!;
        const now = sites.findIndex((x) => same(x.ll, was1.ll));
        const ev = await evaluateAt({ result, session: { ...s } }, was1.ll, `site #${now + 1}`);
        const v = drivewayView(ev.result)!;
        const view = v.overLimit ?? v.routes[0]!;
        graysonCard = [
          `Engine 10 ranked it #1; it is #${now + 1} now. Its driveway section, as the card shows it (evaluated at the site):`,
          "",
          `> ${v.note}`,
          ">",
          `> **${view.title}** ${view.from} · ${view.cost}`,
          ...view.rows.map((r) => `> - ${r.label}: ${r.value}${r.strong ? ` **${r.strong}**` : ""}`),
          "",
          "The routes through the neighbours differ by a few feet between the ranking (6,233 ft, every site searched " +
            "together) and the card (one site): the weighted A* (×1.25) settles a little differently for one target than " +
            "for several, as since #98.",
          "",
          "The paragraph leads the section (the owner's placement); the routes below it are unchanged in form. The gate " +
            'panel\'s warn ("drive needs a steeper paved alignment or an easement") comes with B2.',
        ];
      }
    }

    out.push(
      "",
      "## 2. Sites that trip the rule",
      "",
      `Over ${k$(K.impracticalShareOfReadyToBuild * 300_000)} (the default budget). Each is scored on the alternative with fewer points; the ${K.practicalMaxPct}% route carries the over-limit term at its design limit (+5 under a 10% limit; option C), the route through the neighbours the easement term (+10). The over-limit terms in the table are those scored.`,
      "",
      "| Site (engine 10 rank) | Chosen route | Steeper alternative | Easement alternative | Score with the rule (rank) / without |",
      "|---|---|---|---|---|",
      ...(trips.length ? trips : ["| none | | | | |"]),
      "",
      "## 3. Rankings",
      "",
      ...rankings,
      "## 4. Grayson's 1.28 ac site on the card",
      "",
      ...graysonCard,
      "",
    );
    writeFileSync(DOC, out.join("\n"));
  }, 600_000);
});
