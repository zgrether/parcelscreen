/**
 * The 15% grade limit and the 25% veto (owner, #103 decisions, 2026-10-11; ENGINE_VERSION 13). Writes
 * docs/studies/driveway-defaults.md: every fixture site's scored driveway before (engine 12, at 10% and 20%, from
 * driveway-defaults.before.json) and now, the driveway sections, the paving lengths the cards now show, and the sites
 * that still trip "no practical drive".
 *
 *   pnpm dw:defaults
 */
import { readFileSync, writeFileSync } from "node:fs";
import { describe, it } from "vitest";
import { derivedSites } from "@/lib/screen/derive";
import { DEFAULT_USER_CONFIG, SCREEN_CONSTANTS } from "@/lib/screen/config";
import { overLimitSpans, siteDriveways, type SiteDriveway } from "@/lib/screen/driveway";
import { ENGINE_VERSION } from "@/lib/screen/engine";
import { routeContext } from "@/lib/screen/index";
import { chooseDriveway } from "@/lib/screen/score";
import type { LatLon } from "@/lib/screen/util";
import { M2FT } from "@/lib/screen/util";
import { runFixture } from "../support/scenarios";

const DOC = "docs/studies/driveway-defaults.md";
const K = SCREEN_CONSTANTS.driveway;
const SLUGS = [
  ["ferney-creek-52-47A", "Ferney"],
  ["macks-mountain-35-3", "Macks"],
  ["grayson-mud-creek-6273", "Grayson"],
] as const;

interface Brief {
  lengthFt: number;
  costMid: number;
  switchbacks: number;
  maxGradePct: number;
  needsEasement: boolean;
  legal?: boolean;
  label?: string;
}
interface BeforeSite {
  rank: number;
  ll: LatLon;
  acres: number;
  score: number;
  drivewayPts: number;
  driveFt: number | null;
  chosen: Brief | null;
  practical: { scoredOn: string | null; costMid: number } | null;
}
type Before = {
  engine: number;
  target: Record<string, { toLabel: string; overLimit: Brief | null; routes: Brief[] }>;
} & Record<string, BeforeSite[]>;
const BEFORE = JSON.parse(readFileSync("test/tools/driveway-defaults.before.json", "utf8")) as Before;

const f0 = (x: number) => Math.round(x).toLocaleString("en-US");
const k$ = (x: number) => `$${Math.round(x / 1000)}k`;
const same = (a: LatLon, b: LatLon) => a[0] === b[0] && a[1] === b[1];
const pavedFt = (profile: readonly (readonly [number, number])[]) =>
  overLimitSpans(profile as [number, number][], K.paveAbovePct / 100).reduce((t, [a, b]) => t + (b - a), 0) *
  M2FT;
const brief = (b: Brief | null) =>
  b
    ? `${f0(b.lengthFt)} ft, ${b.maxGradePct.toFixed(1)}%, ${b.switchbacks} sw, ${k$(b.costMid)}${b.needsEasement ? ", easement" : ""}${b.legal === false ? ", over the limit" : ""}`
    : "none";
const now = (d: SiteDriveway | null) =>
  d?.route
    ? brief({
        lengthFt: d.route.metrics.lengthFt,
        costMid: d.route.cost.mid,
        switchbacks: d.route.metrics.switchbacks,
        maxGradePct: d.route.metrics.maxGradePct,
        needsEasement: d.route.needsEasement,
        legal: d.legal,
      }) + `, paving ~${f0(pavedFt(d.route.profile))} ft`
    : "none";

describe.runIf(import.meta.env.MODE === "dw-defaults")("the 15% grade limit and 25% veto", () => {
  it("writes the study", async () => {
    const C = DEFAULT_USER_CONFIG;
    const out: string[] = [
      "# The 15% grade limit and the 25% veto",
      "",
      `Generated by \`pnpm dw:defaults\` (\`test/tools/driveway-defaults.test.ts\`), engine ${BEFORE.engine} → ${ENGINE_VERSION}. ` +
        `The owner's #103 decisions (2026-10-11): the grade limit's default ${10}% → ${C.roadMaxGradePct}%, the veto ` +
        `20% → ${C.roadVetoGradePct}% (ground over 30 m), every route card shows its length over ${K.paveAbovePct}% as ` +
        'paving (cost TBD), and the "no practical drive" rule\'s steeper alternative only when the limit is below ' +
        `${K.practicalMaxPct}%. Costs are the middle of the ±30% range; paving isn't priced.`,
      "",
      "## 1. Every fixture site's scored driveway",
      "",
      "| Site (engine 12 rank) | Before: scored route (10%) | Now: scored route (15%) | Points | Score (rank) |",
      "|---|---|---|---|---|",
    ];
    const targets: string[] = [];
    const trips: string[] = [];
    for (const [slug, name] of SLUGS) {
      const { result, session: s } = await runFixture(slug);
      const sites = derivedSites(result) ?? [];
      const routes = siteDriveways(
        routeContext(s),
        s.roads ?? [],
        s.parcel,
        sites.map((x) => x.ll),
        s.config.roadMaxGradePct,
      );
      for (const b of BEFORE[slug]!) {
        const i = sites.findIndex((x) => same(x.ll, b.ll));
        if (i < 0) {
          out.push(
            `| ${name} #${b.rank} (${b.acres.toFixed(2)} ac) | ${brief(b.chosen)} | not ranked now | | |`,
          );
          continue;
        }
        const x = sites[i]!;
        const chosen = chooseDriveway(routes[i]!, s.config.roadVetoGradePct);
        out.push(
          `| ${name} #${b.rank} (${b.acres.toFixed(2)} ac) | ${brief(b.chosen)}${b.practical ? ` (no practical drive: scored on the ${b.practical.scoredOn})` : ""} | ` +
            `${now(chosen)}${x.practical ? ` (no practical drive: scored on ${x.practical.scoredOn ?? "it"})` : ""} | ` +
            `${b.drivewayPts.toFixed(1)} → ${x.c.driveway.toFixed(1)} | ${b.score} (#${b.rank}) → ${x.score} (#${x.rank}) |`,
        );
        if (x.practical)
          trips.push(
            `${name} #${x.rank} (${x.acres.toFixed(2)} ac): chosen route ${k$(x.practical.cost.mid)}`,
          );
      }
      // The driveway section.
      const tb = BEFORE.target[slug]!;
      const d = result.driveway!;
      const lines = (o: typeof d.overLimit, rs: typeof d.routes) =>
        [...(o ? [o] : []), ...rs].map(
          (r) =>
            `${r.label}${r.needsEasement ? " (easement)" : ""}${o === r ? " (over the limit)" : ""}: ${f0(r.metrics.lengthFt)} ft, ` +
            `${r.metrics.maxGradePct.toFixed(1)}% over 30 m, ${r.metrics.switchbacks} switchbacks, ${k$(r.cost.mid)}, ` +
            `paving ~${f0(pavedFt(r.profile))} ft`,
        );
      targets.push(
        `**${name}, ${d.toLabel}.** Before (10%): ${[
          ...(tb.overLimit ? [{ ...tb.overLimit, over: true }] : []),
          ...tb.routes,
        ]
          .map(
            (r) =>
              `${r.label ?? ""}${r.needsEasement ? " (easement)" : ""}${"over" in r ? " (over the limit)" : ""}: ${f0(r.lengthFt)} ft, ${r.maxGradePct.toFixed(1)}%, ${r.switchbacks} switchbacks, ${k$(r.costMid)}`,
          )
          .join("; ")}.`,
        "",
        `Now (15%): ${lines(d.overLimit, d.routes).join("; ")}.${d.practical ? ' The section leads with "No practical drive".' : ""}`,
        "",
      );
    }
    out.push(
      "",
      "## 2. The driveway sections",
      "",
      ...targets,
      '## 3. "No practical drive" at the new defaults',
      "",
      trips.length
        ? `Still over ${Math.round(K.impracticalShareOfReadyToBuild * 100)}% of the ready-to-build budget: ${trips.join("; ")}. ` +
            `At a ${C.roadMaxGradePct}% limit there is no steeper alternative (it would be ${K.practicalMaxPct}%), so the ` +
            "rule offers the route through the neighbours, if any."
        : `No site's scored route costs more than ${Math.round(K.impracticalShareOfReadyToBuild * 100)}% of the ready-to-build ` +
            `budget at a ${C.roadMaxGradePct}% limit: the rule doesn't trip on the fixtures. (Before, at 10%, it tripped ` +
            "Grayson's 1.28, 0.46 and 0.63 ac sites and Macks #4.)",
      "",
    );
    writeFileSync(DOC, out.join("\n"));
  }, 600_000);
});
